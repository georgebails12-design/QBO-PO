// Today's moves -> QBO journal entries, Dr COGS / Cr WIP per job and category
// (reversed when picks were taken back out after a move). The QBO customer is
// matched from the WASP customer name exactly as the WIP JE matches it, so the
// credit lands on the same customer the WIP debit did; jobs whose customer
// does not resolve to one QBO customer are held (they never got into WIP).
// One JE per TxnDate: the job's Date Completed, or today for later top-ups.
// Output: one item per JE, or one { noEntries } item.
const S = $('Settings').first().json;
const B = $('Build Moves').first().json;
const r2 = n => Math.round((Number(n) || 0) * 100) / 100;

const custMap = {};
const custIssue = {};
const names = $('Distinct Customers').all().map(i => i.json.customer_number);
$input.all().forEach((i, idx) => {
  const n = names[idx];
  if (!n) return;
  const m = (i.json.QueryResponse && i.json.QueryResponse.Customer) || [];
  if (m.length === 1) custMap[n] = { value: m[0].Id, name: m[0].DisplayName };
  else custIssue[n] = m.length === 0 ? 'no QBO customer match for "' + n + '"' : m.length + ' QBO customers match "' + n + '"';
});

const held = [...B.held];
const byDate = {};
for (const c of B.candidates) {
  const cust = custMap[c.customerNumber];
  if (!cust) {
    held.push({ job: c.job, reason: (c.customerNumber ? custIssue[c.customerNumber] : 'picks have no WASP customer') || 'customer lookup failed', amount: c.delta, account: c.acct.wip });
    continue;
  }
  const txnDate = c.topUp ? S.today : c.completed;
  (byDate[txnDate] = byDate[txnDate] || []).push({ ...c, cust });
}

const out = [];
for (const txnDate of Object.keys(byDate).sort()) {
  const [Y, M, D] = txnDate.split('-');
  const docNumber = 'COGS ' + Number(M) + '/' + Number(D) + '/' + Y;
  const lines = [];
  const moves = [];
  let total = 0;
  for (const c of byDate[txnDate].sort((a, b) => a.job.localeCompare(b.job))) {
    const amt = Math.abs(c.delta);
    const desc = ('Job ' + c.job + ' ' + c.production + ' - ' + c.acct.wip + ' to ' + c.acct.cogs + (c.topUp ? ' (picks after move)' : '') + ' - picks ' + c.picks).slice(0, 4000);
    const entity = { EntityRef: c.cust, Type: 'Customer' };
    const dr = c.delta > 0 ? c.acct.cogsId : c.acct.wipId;
    const cr = c.delta > 0 ? c.acct.wipId : c.acct.cogsId;
    lines.push({ Description: desc, Amount: amt, DetailType: 'JournalEntryLineDetail', JournalEntryLineDetail: { PostingType: 'Debit', AccountRef: { value: dr }, Entity: entity } });
    lines.push({ Description: desc, Amount: amt, DetailType: 'JournalEntryLineDetail', JournalEntryLineDetail: { PostingType: 'Credit', AccountRef: { value: cr }, Entity: entity } });
    total += c.delta;
    moves.push({
      job: c.job, shop_item_id: c.shopItemId, job_type: c.jobType, date_completed: c.completed,
      wip_account: c.acct.wip, wip_account_id: c.acct.wipId, cogs_account: c.acct.cogs, cogs_account_id: c.acct.cogsId,
      amount: c.delta, customer_qbo_id: c.cust.value, customer_name: c.cust.name, picks: c.picks,
      txn_date: txnDate, je_doc: docNumber, production: c.production, open_picks: c.openPicks, top_up: c.topUp,
    });
  }
  out.push({ json: {
    txnDate, docNumber, total: r2(total), moves, shouldPost: !S.dryRun,
    payload: { TxnDate: txnDate, DocNumber: docNumber,
      PrivateNote: 'WIP to COGS for Shop Updates jobs completed - auto-generated by the Daily WIP to COGS n8n workflow.',
      Line: lines },
  } });
}
if (!out.length) return [{ json: { noEntries: true, shouldPost: false, heldAfterLookup: held } }];
out[0].json.heldAfterLookup = held;
return out;
